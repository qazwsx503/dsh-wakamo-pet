#!/usr/bin/env python3
"""Inline the pet frames into client.js as data URLs.

Plain-JS client bundles are served as one module, so the artwork is embedded
instead of fetched from a separate route. Edit src/client.template.js, then
run this script to regenerate client.js.
"""
import base64
import pathlib

ROOT = pathlib.Path(__file__).resolve().parent.parent
FRAMES = [
    "idle",
    "s2_01",
    "s2_04",
    "s2_07",
    "s2_09",
    "s2_12",
    "s2_13",
]
VOICES = [
    "login",
    "serve",
    "mask",
    "unmask",
    "stare",
    "prepared",
    "dontLeave",
    "satisfied",
    "end",
    "watching",
    "victory",
    "headpat",
    "summer",
    "walk",
    "size",
    "headpatLong",
    "touch",
    "move",
    "cool",
    "thanks",
    "beside",
    "close",
]


def data_url(name: str) -> str:
    raw = (ROOT / "assets" / f"{name}.webp").read_bytes()
    return "data:image/webp;base64," + base64.b64encode(raw).decode("ascii")


def voice_base64(name: str) -> str:
    raw = (ROOT / "assets" / "voices" / f"{name}.ogg").read_bytes()
    return base64.b64encode(raw).decode("ascii")


def main() -> None:
    template = (ROOT / "src" / "client.template.js").read_text(encoding="utf-8")
    file_tools = (ROOT / "src" / "file-tools.client.js").read_text(encoding="utf-8")
    template = template.replace("    // FILE_TOOLS_COMPONENT", file_tools)
    lines = ["(function () {", "const ASSETS = {"]
    for name in FRAMES:
        lines.append(f'  {name}: "{data_url(name)}",')
    lines.append("};")
    lines.append("const VOICES = {")
    for name in VOICES:
        lines.append(f'  {name}: "{voice_base64(name)}",')
    lines.append("};")
    lines.append("const HAND_FRAMES = [")
    for index in range(5):
        raw = (ROOT / "assets" / "hand" / f"{index}.png").read_bytes()
        lines.append(f'  "data:image/png;base64,{base64.b64encode(raw).decode("ascii")}",')
    lines.append("];")
    eye = (ROOT / "assets" / "eye-blink.png").read_bytes()
    lines.append('const EYE_PATCH = "data:image/png;base64,' + base64.b64encode(eye).decode("ascii") + '";')
    lines.append(template)
    lines.append("})();")
    output = "// Generated by src/build_assets.py - edit src/client.template.js instead.\n" + "\n".join(lines) + "\n"
    target = ROOT / "client.js"
    target.write_text(output, encoding="utf-8")
    print(f"wrote {target} ({target.stat().st_size / 1024 / 1024:.2f} MB)")


if __name__ == "__main__":
    main()
